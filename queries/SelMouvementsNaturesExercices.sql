SELECT
  TBLMOUVEMENTS.MvtSocNum,
  TBLMOUVEMENTS.MvtDate,
  TBLMOUVEMENTSNATURES.MvtNatNum,
  TBLMOUVEMENTSNATURES.MvtNatCode,
  TBLEXERCICES.ExeNum,
  TBLEXERCICES.ExeExercice,
  TBLMOUVEMENTS.MvtIntitule,
  TBLMOUVEMENTS.MvtDebit,
  TBLMOUVEMENTS.MvtCredit,
  TBLMOUVEMENTS.MvtQuantite,
  TBLMOUVEMENTS.MvtNum,
  TBLMOUVEMENTS.MvtDossier
FROM
  TBLMOUVEMENTSNATURES
  INNER JOIN (
    TBLEXERCICES
    INNER JOIN TBLMOUVEMENTS ON TBLEXERCICES.ExeNum = TBLMOUVEMENTS.MvtExeNum
  ) ON TBLMOUVEMENTSNATURES.MvtNatNum = TBLMOUVEMENTS.MvtMvtNatNum
ORDER BY
  TBLMOUVEMENTS.MvtDate DESC,
  TBLMOUVEMENTS.MvtNum DESC;
