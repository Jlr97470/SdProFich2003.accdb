SELECT
  TBLCONTACTS.ConNom,
  TBLCONTACTS.ConPrenom,
  TBLCONTACTSFONCTIONS.ConFonCode,
  TBLCONTACTSFONCTIONS.ConFonLibelle,
  TBLCONTACTS.ConNum,
  TBLCONTACTS.ConSocNum
FROM
  TBLCONTACTSFONCTIONS
  INNER JOIN TBLCONTACTS ON TBLCONTACTSFONCTIONS.ConFonCode = TBLCONTACTS.ConFonCode
ORDER BY
  TBLCONTACTSFONCTIONS.ConFonCode DESC,
  TBLCONTACTS.ConNom;
