SELECT DISTINCTROW
  TBLSOCIETESADHERENTS.SocAdhNum,
  TBLSOCIETESADHERENTS.SocAdhSocNum,
  TBLEXERCICES.ExeExercice,
  TBLEXERCICES.ExeLibelle,
  TBLSOCIETESADHERENTS.SocAdhDate,
  TBLSOCIETESADHERENTS.SocAdhEtat
FROM
  TBLEXERCICES
  INNER JOIN TBLSOCIETESADHERENTS ON TBLEXERCICES.ExeNum = TBLSOCIETESADHERENTS.SocAdhExeNum
ORDER BY
  TBLSOCIETESADHERENTS.SocAdhSocNum,
  TBLSOCIETESADHERENTS.SocAdhDate DESC,
  TBLEXERCICES.ExeLibelle DESC;
